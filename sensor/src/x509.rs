    #[test]
    fn self_signed_cert_fields() {
        let info = parse_certificate(SELF_DER).expect("自签证书应能解析");
        assert_eq!(info.subject_cn.as_deref(), Some("evil.selfsigned"));
        assert_eq!(info.issuer_cn.as_deref(), Some("evil.selfsigned"));
        assert!(info.self_signed, "subject==issuer 应判自签");
        // 2026-08-09 14:42:45Z 起一年
        assert_eq!(info.not_before, 1_786_286_565);
        assert_eq!(info.not_after, 1_817_822_565);
        assert_eq!(
            info.not_after - info.not_before,
            365 * 86400,
            "有效期应恰好一年"
        );
    }

    #[test]
    fn ca_signed_cert_fields() {
        let info = parse_certificate(LEAF_DER).expect("CA 签发证书应能解析");
        assert_eq!(info.subject_cn.as_deref(), Some("leaf.example"));
        assert_eq!(info.issuer_cn.as_deref(), Some("Test CA"));
        assert!(!info.self_signed, "issuer 不同不应判自签");
        assert_eq!(info.not_before, 1_786_286_566);
        assert_eq!(info.not_after, 1_817_822_566);
    }

    #[test]
    fn truncated_der_returns_none_no_panic() {
        // 所有前缀截断都不能 panic，且一定解析不出来
        for cut in 0..SELF_DER.len() {
            assert!(
                parse_certificate(&SELF_DER[..cut]).is_none(),
                "截断到 {cut} 字节应返回 None"
            );
        }
    }

    #[test]
    fn malformed_der_returns_none_no_panic() {
        assert!(parse_certificate(b"").is_none());
        assert!(parse_certificate(&[0x30]).is_none());
        assert!(parse_certificate(&[0x30, 0x82, 0xff, 0xff]).is_none());
        // 不定长形式在 DER 里非法
        assert!(parse_certificate(&[0x30, 0x80, 0x00, 0x00]).is_none());
        // 翻转若干字节不应 panic
        for pos in [0usize, 5, 60, 90, SELF_DER.len() - 1] {
            let mut bad = SELF_DER.to_vec();
            bad[pos] ^= 0xff;
            let _ = parse_certificate(&bad);
        }
    }

    #[test]
    fn utc_time_year_pivot() {
        // YY < 50 → 20YY；YY >= 50 → 19YY（RFC 5280）
        assert_eq!(parse_time(0x17, b"490101000000Z"), Some(2_493_072_000)); // 2049-01-01
        assert_eq!(parse_time(0x17, b"500101000000Z"), Some(-631_152_000)); // 1950-01-01
        assert_eq!(parse_time(0x17, b"700101000000Z"), Some(0)); // 1970-01-01 即 epoch
    }

    #[test]
    fn generalized_time_parsing() {
        assert_eq!(
            parse_time(0x18, b"20500101000000Z"),
            Some(2_524_608_000),
            "GeneralizedTime YYYYMMDDHHMMSSZ"
        );
        // 闰日换算：2024-02-29
        assert_eq!(parse_time(0x18, b"20240229120000Z"), Some(1_709_208_000));
    }

    #[test]
    fn time_rejects_malformed() {
        assert_eq!(parse_time(0x17, b"260809144245"), None, "缺 Z 拒收");
        assert_eq!(parse_time(0x17, b"26080914424Z"), None, "少一位拒收");
        assert_eq!(parse_time(0x18, b"20241301000000Z"), None, "13 月拒收");
        assert_eq!(parse_time(0x18, b"20240101240000Z"), None, "24 时拒收");
        assert_eq!(parse_time(0x06, b"260809144245Z"), None, "非时间 tag 拒收");
    }

//! 迷你 X.509 证书解析：从 TLS Certificate 消息拿到的 DER 证书中，
//! 提取 subject/issuer 的 CN、自签启发式与有效期。
//! 手写 DER TLV walker，不引外部 crate；任何畸形一律返回 None，绝不 panic。

/// 从一张叶证书 DER 提取出的元数据
pub struct CertInfo {
    /// subject 的 CN（OID 2.5.4.3），没有则为 None
    pub subject_cn: Option<String>,
    /// issuer 的 CN
    pub issuer_cn: Option<String>,
    /// 自签启发式：subject 与 issuer 的原始 DER 切片逐字节相等。
    /// 不做签名验证——被动嗅探只图一个高价值标记，误判代价低。
    pub self_signed: bool,
    /// 有效期起（unix 秒）
    pub not_before: i64,
    /// 有效期止（unix 秒）
    pub not_after: i64,
}

/// DER TLV：tag + 内容切片 + 含头完整切片（raw 供 issuer/subject 比对用）
struct Tlv<'a> {
    tag: u8,
    body: &'a [u8],
    raw: &'a [u8],
}

/// 读一个 TLV，返回它本身与剩余字节。
/// 长度只支持定长形式（short form 与 ≤4 字节的 long form），不定长一律判畸形。
fn read_tlv(buf: &[u8]) -> Option<(Tlv<'_>, &[u8])> {
    let tag = *buf.first()?;
    let len_byte = *buf.get(1)?;
    let (len, hdr) = if len_byte & 0x80 == 0 {
        (len_byte as usize, 2)
    } else {
        let n = (len_byte & 0x7f) as usize;
        // 0 是不定长形式，DER 不允许；超过 4 字节的长度也不可信
        if n == 0 || n > 4 {
            return None;
        }
        let mut len = 0usize;
        for b in buf.get(2..2 + n)? {
            len = (len << 8) | *b as usize;
        }
        (len, 2 + n)
    };
    let body = buf.get(hdr..hdr + len)?;
    let raw = buf.get(..hdr + len)?;
    let rest = buf.get(hdr + len..)?;
    Some((Tlv { tag, body, raw }, rest))
}

/// 解析一张 X.509 证书 DER（Certificate ::= SEQUENCE { tbsCertificate, ... }）。
pub fn parse_certificate(der: &[u8]) -> Option<CertInfo> {
    let (cert, rest) = read_tlv(der)?;
    // 必须恰好一个顶层 SEQUENCE，多余尾巴判畸形
    if cert.tag != 0x30 || !rest.is_empty() {
        return None;
    }
    let (tbs, _) = read_tlv(cert.body)?;
    if tbs.tag != 0x30 {
        return None;
    }

    // TBSCertificate: [0] version(可选) → serial → signature → issuer → validity → subject
    let mut cur = tbs.body;
    let (first, r) = read_tlv(cur)?;
    cur = r;
    if first.tag == 0xa0 {
        // 有显式 version 字段，下一个才是 serial
        let (serial, r2) = read_tlv(cur)?;
        if serial.tag != 0x02 {
            return None;
        }
        cur = r2;
    } else if first.tag != 0x02 {
        return None; // 没有 version 字段时第一个必须是 serial INTEGER
    }
    let (sig, r) = read_tlv(cur)?; // signature AlgorithmIdentifier
    if sig.tag != 0x30 {
        return None;
    }
    cur = r;
    let (issuer, r) = read_tlv(cur)?;
    if issuer.tag != 0x30 {
        return None;
    }
    cur = r;
    let (validity, r) = read_tlv(cur)?;
    if validity.tag != 0x30 {
        return None;
    }
    let (subject, _) = read_tlv(r)?;
    if subject.tag != 0x30 {
        return None;
    }

    let (nb, r) = read_tlv(validity.body)?;
    let (na, _) = read_tlv(r)?;
    let not_before = parse_time(nb.tag, nb.body)?;
    let not_after = parse_time(na.tag, na.body)?;

    Some(CertInfo {
        subject_cn: find_cn(subject.body),
        issuer_cn: find_cn(issuer.body),
        self_signed: subject.raw == issuer.raw,
        not_before,
        not_after,
    })
}

/// CN 的 OID 2.5.4.3 在 DER 里的内容字节
const OID_CN: &[u8] = &[0x55, 0x04, 0x03];

/// 在 RDNSequence（SEQUENCE OF SET OF AttributeTypeAndValue）里找第一个 CN。
fn find_cn(name_body: &[u8]) -> Option<String> {
    let mut rest = name_body;
    while let Some((set, r)) = read_tlv(rest) {
        rest = r;
        if set.tag != 0x31 {
            continue;
        }
        let (atv, _) = read_tlv(set.body)?;
        if atv.tag != 0x30 {
            return None;
        }
        let (oid, after_oid) = read_tlv(atv.body)?;
        if oid.tag != 0x06 {
            return None;
        }
        if oid.body == OID_CN {
            let (value, _) = read_tlv(after_oid)?;
            // UTF8String / PrintableString / TeletexString，统一按 lossy UTF-8 取
            if matches!(value.tag, 0x0c | 0x13 | 0x14) {
                return Some(String::from_utf8_lossy(value.body).into_owned());
            }
        }
    }
    None
}

/// 解析 X.509 时间：UTCTime(0x17, YYMMDDHHMMSSZ) 与 GeneralizedTime(0x18, YYYYMMDDHHMMSSZ)。
/// 只接受带 Z 的 UTC 形式，其他写法一律判畸形。
fn parse_time(tag: u8, body: &[u8]) -> Option<i64> {
    let s = std::str::from_utf8(body).ok()?;
    let (year, rest) = match tag {
        0x17 => {
            let yy = two_digits(s, 0)?;
            // RFC 5280：YY < 50 算 20YY，否则 19YY
            (if yy < 50 { 2000 + yy } else { 1900 + yy }, s.get(2..)?)
        }
        0x18 => (four_digits(s, 0)?, s.get(4..)?),
        _ => return None,
    };
    // 剩余必须是 MMDDHHMMSSZ
    if rest.len() != 11 || !rest.ends_with('Z') {
        return None;
    }
    let month = two_digits(rest, 0)?;
    let day = two_digits(rest, 2)?;
    let hour = two_digits(rest, 4)?;
    let minute = two_digits(rest, 6)?;
    let second = two_digits(rest, 8)?;
    if !(1..=12).contains(&month)
        || !(1..=31).contains(&day)
        || hour > 23
        || minute > 59
        || second > 59
    {
        return None;
    }
    let days = days_from_civil(year, month, day);
    Some(days * 86400 + hour * 3600 + minute * 60 + second)
}

fn two_digits(s: &str, pos: usize) -> Option<i64> {
    let b = s.as_bytes();
    let hi = b.get(pos)?.wrapping_sub(b'0');
    let lo = b.get(pos + 1)?.wrapping_sub(b'0');
    if hi > 9 || lo > 9 {
        return None;
    }
    Some((hi * 10 + lo) as i64)
}

fn four_digits(s: &str, pos: usize) -> Option<i64> {
    Some(two_digits(s, pos)? * 100 + two_digits(s, pos + 2)?)
}

/// 格里高利历日期 → 自 1970-01-01 的天数（days-from-civil 算法，不引 chrono）。
fn days_from_civil(y: i64, m: i64, d: i64) -> i64 {
    let y = if m <= 2 { y - 1 } else { y };
    let era = if y >= 0 { y } else { y - 399 } / 400;
    let yoe = y - era * 400; // [0, 399]
    let mp = if m > 2 { m - 3 } else { m + 9 }; // [0, 11]，3 月为 0
    let doy = (153 * mp + 2) / 5 + d - 1;
    let doe = yoe * 365 + yoe / 4 - yoe / 100 + doy;
    era * 146097 + doe - 719468
}

